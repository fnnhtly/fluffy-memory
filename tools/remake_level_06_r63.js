/* 第 63 轮：重建 1-6 的地形，让"浮力过沟"真正成立。
 *
 * ── 为什么要重做 ──
 * 旧的 1-6 是为"气球浮力直接加到车心"那个模型设计的：
 * 沟在 col 11（宽 1 格）、崖壁几乎垂直（slope -4.14 → +7.69）。
 * 车靠浮力"飘"起来的时候，浮力不区分位置，整台车均匀变轻，
 * 所以只要 netMass < 0 就能整体离地漂过沟。
 *
 * 新的模型里热气球是**挂在框上方的一个零件**，浮力仍加在车心上
 * （这点没变），但多了两条硬约束：
 *   1) 球必须系在框上方，否则飘走 —— 摆位变严了；
 *   2) 驱动件/气球的位置参与力矩，车会低头抬头。
 * 结果是旧地形跑不过去：实测在 x=11.9 卡住（崖壁前），
 * 各档 liftMass（1.5~2.5）× 沙袋数（2/3）扫了一遍，
 * 最好的一档也只能到 x=14.6，而终点在 15 —— 差一点点，纯几何问题。
 *
 * ── 改了什么 ──
 * 把沟加宽、崖壁放缓：原来的 (11,12,13) hardCols 造成一道 1.5 米宽、
 * 4 米高的窄峭壁，车必须"垂直起飞"才过得去。
 * 现在改成一道**斜上的坡**：先下到沟底，再从右侧一层层爬上去。
 * 这样"浮力够不够"变成一个连续可调的判断（多一个球就能多爬一层），
 * 而不是"过/不过"的悬崖 —— 这才是参考里气球关的样子。
 *
 * ⚠ 这个脚本是**一次性迁移**，跑完就不该再跑（它会覆盖 06.json）。
 *   之所以写成脚本而不是手改：JSON 里有中文，PowerShell 文本往返
 *   已经把这个文件的 name 字段写成「鎶个澶?」乱码一次了。
 */
