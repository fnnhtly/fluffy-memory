import pathlib

q = pathlib.Path("records/playtest.md")
r = q.read_text(encoding="utf-8")
add = """## 2026-11-13 · 组件保持平面连接 + 只有轮子能转（runtime=html，执行者：Agent）

**用户要求**：「各个组件要像组装的时候保持平面连接，除轮子等能转动的组件能转外，组件本身不能转动」

### 诊断结果：数据层本来就是刚体

用 `tools/debug_rigid.js` 把车固定在 0 / 0.35 / -0.6 弧度，读出每个零件的绘制角度：

```
a=0.35 → 木框 20.1° / 木框 20.1° / 猪 20.1° / 木框 20.1° / 轮 20.1° / 轮 20.1°
```

**所有零件角度完全一致**，没有相对转动。所以问题不在物理，在渲染。

### 真因：零件之间留了缝

每个零件只画到 **0.86 格**（建造界面 0.88），相邻木框之间因此留了 5~6px 的缝。
视觉上就是"几个漂浮的方框拼在一起"，车体倾斜时缝隙会被放大，看起来像零件各自在转。

### 修法

| 项 | 之前 | 现在 |
|---|---|---|
| 行驶时零件尺寸 | 0.86 格 | **1.0 格**（满格，边框严丝合缝） |
| 建造时零件尺寸 | 0.88 格 | **1.0 格** |
| 内嵌件（猪） | 0.60 格 | 0.62 格（仍留一点内壁） |
| 轮子 | 跟随车体角度 | **满格 + 按里程自转**（唯一允许转动的组件） |

### 轮子自转实现
物理层加 `car.odo`（累计里程），渲染时 `spin = odo / radius`，
只对 `def.wheel` 生效；木框/马达等 `baseRot` 只用车体角度，不含 spin。

### 顺带修了 shot-diff 误报
`ls-04-thumb.png` 是选关页（不画车辆零件），零件外观改动时它当然不变，
从 WATCH 列表移除，避免每次误报"改动没生效"。

回归：34/34 + 十个脚本 0 异常；`shot-diff compare` **7/7 全部变化**。

"""
marker = "## 已知弱点（如实记录）"
assert marker in r
r = r.replace(marker, add + marker)
q.write_text(r, encoding="utf-8")
print("记录已补")
